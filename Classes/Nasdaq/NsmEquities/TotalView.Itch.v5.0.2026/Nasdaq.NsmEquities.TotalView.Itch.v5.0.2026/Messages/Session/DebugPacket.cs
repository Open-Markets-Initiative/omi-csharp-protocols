    bool IFieldOwner.IsRecognized(int field) => true;

    bool IFieldOwner.IsPresent(int field) => true;

    bool IFieldOwner.IsParsed(int field) => this.status == ParseStatus.Ok || field < (int?)this.failed;

    bool IFieldOwner.IsReached(int field) => this.modified || this.status is ParseStatus.None or ParseStatus.Ok || field <= (int?)this.failed;

    bool IFieldOwner.HasParseLayout(int field) => false;

    int IFieldOwner.OffsetOf(int field) => (FieldName)field switch
    {
        FieldName.ClientMessageCode => FieldView.NotInMessage,
        FieldName.ServerMessageCode => FieldView.NotInMessage,
        FieldName.DebugText => DebugTextOffset,
        _ => throw new ArgumentOutOfRangeException(nameof(field)),
    };

    int IFieldOwner.LengthOf(int field) => (FieldName)field switch
    {
        FieldName.ClientMessageCode => ClientMessageCodeLength,
        FieldName.ServerMessageCode => ServerMessageCodeLength,
        FieldName.DebugText => TextEncoding.Ascii.ByteCount(TextEncoding.Ascii.Holdable(this.debugText)),
        _ => throw new ArgumentOutOfRangeException(nameof(field)),
    };

    IReadOnlyList<IGroupEntry>? IFieldOwner.EntriesOf(int field) => null;

    IMessage? IFieldOwner.MessageOf(int field) => null;

    ulong[] IFieldOwner.ChangedAgainst(IFieldOwner other) => other is DebugPacket typed ? Diff(typed).ToWords() : throw new ArgumentException("The other instance is not of the same type.", nameof(other));

    void IFieldOwner.CopyField(int field, IFieldOwner from) => CopyField((FieldName)field, from as DebugPacket ?? throw new ArgumentException("The other instance is not of the same type.", nameof(from)));

    ReadOnlyMemory<byte> IFieldOwner.CodeBytes(int field)
    {
        if (field == (int)FieldName.ClientMessageCode)
        {
            var bytes = new byte[ClientMessageCodeLength];
            bytes[0] = unchecked((byte)(ClientMessageCode.DebugPacket));
            return bytes;
        }
        if (field == (int)FieldName.ServerMessageCode)
        {
            var bytes = new byte[ServerMessageCodeLength];
            bytes[0] = unchecked((byte)(ServerMessageCode.DebugPacket));
            return bytes;
        }
        return ReadOnlyMemory<byte>.Empty;
    }
